#!/usr/bin/env node
// Generates config/abis.ts (typed `as const` ABIs) from Foundry artifacts in contracts/out.
// Run `forge build` (in /contracts) first. Usage: node scripts/gen-abis.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const contracts = [
  "Settlement",
  "MidpointPool",
  "MakerRegistry",
  "FeeCollector",
  "ProjectTokenHooks",
  "PriceGuard",
  "MarketClock",
  "OracleAdapter",
  "ComplianceRegistry",
  "BlockroomTimelock",
];

if (!existsSync(out)) {
  console.error("contracts/out not found - run `forge build` in /contracts first");
  process.exit(1);
}

let src = "// AUTO-GENERATED by scripts/gen-abis.mjs from contracts/out - do not edit.\n\n";
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8"));
  const varName = name.charAt(0).toLowerCase() + name.slice(1) + "Abi";
  src += `export const ${varName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(root, "config", "abis.ts"), src);
console.log(`wrote config/abis.ts (${contracts.length} contracts)`);
