#!/usr/bin/env node
// Collects src/generated/deployments/<chainId>.json (written by contracts/script/Deploy.s.sol) into a single
// typed module so the app builds whether or not a given chain has been deployed yet.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "generated");
const depDir = join(dir, "deployments");
mkdirSync(depDir, { recursive: true });
const out = {};
for (const f of existsSync(depDir) ? readdirSync(depDir) : []) {
  if (!/^\d+\.json$/.test(f)) continue;
  const d = JSON.parse(readFileSync(join(depDir, f), "utf8"));
  out[String(d.chainId)] = d;
}
writeFileSync(
  join(dir, "deployments.ts"),
  `// AUTO-GENERATED by app/scripts/collect-deployments.mjs - do not edit.\n` +
    `import type { Deployment } from "../lib/deployments-type";\n\n` +
    `export const DEPLOYMENTS: Record<string, Deployment> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`deployments: ${Object.keys(out).join(", ") || "(none yet)"}`);
